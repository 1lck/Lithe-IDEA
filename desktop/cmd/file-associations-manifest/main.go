// Command file-associations-manifest projects the editor's actual bundled syntax
// catalog through Core into Viva's native package declarations.
package main

import (
	"bytes"
	"context"
	"flag"
	"fmt"
	"os"
	"strings"
	"time"

	"github.com/1lck/Lithe-IDEA/desktop/internal/core"
	"github.com/1lck/Lithe-IDEA/desktop/internal/fileassociations"
)

const begin = "# BEGIN generated file associations\n"
const end = "# END generated file associations\n"

func main() {
	check := flag.Bool("check", false, "fail if viva.toml differs from the built-in text catalog")
	flag.Parse()
	if err := generate(*check); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generate(check bool) error {
	ctx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
	defer cancel()
	formats, err := fileassociations.Catalog(ctx, core.NewClient())
	if err != nil {
		return err
	}
	source, err := os.ReadFile("viva.toml")
	if err != nil {
		return err
	}
	start := bytes.Index(source, []byte(begin))
	finish := bytes.Index(source, []byte(end))
	if start < 0 || finish < start {
		return fmt.Errorf("viva.toml: missing generated file-association markers")
	}
	var block bytes.Buffer
	block.WriteString(begin)
	block.WriteString("# Generated by scripts/desktop/generate-file-associations.sh; do not edit.\n")
	for _, format := range formats {
		fmt.Fprintf(&block, "[[app.file_types]]\nname = %q\nextensions = [%q]\n\n", "Lithe Desktop "+format.Extension, strings.TrimPrefix(format.Extension, "."))
	}
	block.WriteString(end)
	result := append(bytes.Clone(source[:start]), block.Bytes()...)
	result = append(result, source[finish+len(end):]...)
	if bytes.Equal(result, source) {
		return nil
	}
	if check {
		return fmt.Errorf("viva.toml: file associations are stale; run scripts/desktop/generate-file-associations.sh")
	}
	return os.WriteFile("viva.toml", result, 0644)
}
