#!/usr/bin/env node
// plugin.json owns inert metadata. Both host trust records and plugin factories
// are generated from it; --check prevents hand-maintained declarations drifting.
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
const root = fileURLToPath(new URL("../", import.meta.url));
const check = process.argv.includes("--check");
const plugins = ["Go", "Php"];
const records = [];
async function output(relative, source) {
  const file = path.join(root, relative);
  if (check) {
    if (await readFile(file, "utf8").catch(() => "") !== source)
      throw new Error(`Generated plugin metadata is stale: ${relative}`);
  } else await writeFile(file, source);
}
function decoded(name, manifest) {
  const json = JSON.stringify(manifest);
  if (json.includes('"###')) throw new Error("Unsupported Swift raw-string delimiter in manifest");
  return `    public static let ${name}: PluginManifest = {\n        do { return try JSONDecoder().decode(PluginManifest.self, from: Data(###"${json}"###.utf8)) }\n        catch { preconditionFailure("Invalid generated plugin manifest: \\(error)") }\n    }()\n`;
}
function launches(name, manifest) {
  const projection = JSON.stringify({ languageSupports: manifest.languageSupports });
  return `    public static let ${name}: [String: PluginLanguageServerLaunch] = {\n        do { return try PluginLanguageServerDeclarations.decode(from: Data(###"${projection}"###.utf8)) }\n        catch { preconditionFailure("Invalid generated launch metadata: \\(error)") }\n    }()\n`;
}
for (const language of plugins) {
  const source = `Plugins/mac/Official/${language}Support/plugin.json`;
  const manifest = JSON.parse(await readFile(path.join(root, source), "utf8"));
  const support = manifest.languageSupports[0];
  const execution = manifest.modules.findIndex((module) => module.id === support.executionModuleID);
  const server = manifest.modules.findIndex((module) => module.id === support.languageServerModuleID);
  if (execution < 0 || server < 0 || !support.languageServer) throw new Error(`Incomplete ${source}`);
  records.push(decoded(language.toLowerCase(), manifest) + launches(`${language.toLowerCase()}LanguageServers`, manifest));
  await output(`Plugins/mac/Official/${language}Support/Sources/Lithe${language}SupportModule/Support/${language}SupportManifest.swift`,
    `// Generated by scripts/generate-plugin-manifests.mjs from ${source}.\nimport Foundation\nimport LitheModuleAPI\n\npublic enum ${language}SupportManifest {\n${decoded("plugin", manifest)}${launches("languageServers", manifest)}    public static let languageID = ${JSON.stringify(support.id)}\n    public static let executionModule = plugin.modules[${execution}].manifest\n    public static let languageServerModule = plugin.modules[${server}].manifest\n    public static var languageServerLaunch: PluginLanguageServerLaunch {\n        guard let launch = languageServers[languageID] else {\n            preconditionFailure("Generated plugin launch metadata is missing")\n        }\n        return launch\n    }\n}\n`);
}
await output("macos/Sources/LitheModuleAPI/Catalog/OfficialPluginManifests.generated.swift",
  `// Generated by scripts/generate-plugin-manifests.mjs; edit the owning plugin.json.\nimport Foundation\n\npublic enum OfficialPluginManifests {\n${records.join("\n")} }\n`);

const publisher = JSON.parse(await readFile(path.join(root, "shared/contracts/plugin-publisher.json"), "utf8"));
await output("macos/Sources/LithePluginPackageSigning/PluginPublisherIdentity.generated.swift",
  `// Generated by scripts/generate-plugin-manifests.mjs from shared/contracts/plugin-publisher.json.
` +
  `enum PluginPublisherIdentity {
    static let keyID = ${JSON.stringify(publisher.keyID)}
` +
  `    static let publicKeyBase64 = ${JSON.stringify(publisher.publicKeyBase64)}
}
`);
