FILES = {
    "templates/files/README.md": b"# {{ project.name }}\n{{ field.message }}\n",
    "templates/files/main.mjs": b'console.log("generator files project");\n',
    "templates/files/dot-gitignore": b"node_modules/\n",
    "templates/command/create.mjs": COMMAND_SOURCE,
}


def declaration(archive_url: str, archive_open_file: str) -> dict:
    archive_url = https_base(archive_url)
    if (not archive_open_file or "\\" in archive_open_file
            or any(part in ("", ".", "..") for part in archive_open_file.split("/"))
            or Path(archive_open_file).is_absolute() or ":" in archive_open_file):
        raise ValueError("archive open file must be a nonempty relative ordinary path")
    return {
        "schemaVersion": 2, "id": PLUGIN_ID, "displayName": DISPLAY_NAME,
        "version": "1.0.0", "pluginAPIVersion": 3, "requires": dict(REQUIRES),
        "vendor": {"id": "io.github.lithe-acceptance", "displayName": "Unsigned controlled fixture",
                   "signatureRequirement": "none"},
        "permissions": ["project.generate"], "activationEvents": [],
        "projectGenerators": [
            {"id": "files", "displayName": "Acceptance Files", "section": "project",
             "fields": [{"id": "message", "type": "text", "title": "Message", "default": "A derived template"}],
             "requirements": [{"buildSystemID": "lithe-acceptance-missing"}],
             "steps": [{"kind": "files", "source": "templates/files"}], "openFiles": ["main.mjs"]},
            {"id": "command", "displayName": "Acceptance Command", "section": "generator",
             "fields": [{"id": "mode", "type": "enum", "title": "Mode", "presentation": "segmented",
                         "options": [{"value": value, "title": value.title()}
                                     for value in ("success", "failure", "wait")]}],
             "steps": [{"kind": "files", "source": "templates/command"},
                       {"kind": "command", "command": "node", "arguments": ["create.mjs", "${field.mode}"],
                        "collect": "result", "timeoutSeconds": COMMAND_TIMEOUT_SECONDS, "mayUseNetwork": False}], "openFiles": ["main.mjs"]},
            {"id": "archive", "displayName": "Acceptance Archive", "section": "generator", "fields": [],
             "steps": [{"kind": "archive", "url": archive_url}], "openFiles": [archive_open_file]},
            {"id": "runtime", "displayName": "Acceptance Missing Runtime", "section": "generator",
             "fields": [{"id": "jdk", "type": "runtime", "title": "JDK", "runtime": "java", "minimumVersion": "999"}],
             "steps": [{"kind": "files", "source": "templates/command"}]},
        ],
    }


def check_output(root: Path) -> None:
    parent = ROOT / ".artifacts/plugin-host-acceptance"
    if (parent.resolve() not in root.resolve().parents
            or not root.resolve().relative_to(parent.resolve()).parts[0].startswith("generator-fixture")):
        raise ValueError("use a run-owned generator-fixture below .artifacts/plugin-host-acceptance")
    for path in (root, *root.parents):
        if path.is_symlink() or path.is_junction():
            raise ValueError("fixture path cannot traverse a link")


def archive_input(receipt_path: Path, reference: Path) -> dict:
    """Explicit integration reference, not a download cache or trust exception."""
    receipt = json.loads(receipt_path.read_text(encoding="utf-8-sig"))
    required = {"repository", "commit", "url", "license", "zipSha256", "zipBytes", "entries", "expandedBytes", "expectedOpenFile"}
    if set(receipt) != required or not all(isinstance(receipt[key], str) and receipt[key] for key in
                                         ("repository", "commit", "url", "license", "zipSha256", "expectedOpenFile")):
        raise ValueError("archive reference receipt is incomplete")
    if sha256(reference) != receipt["zipSha256"] or reference.stat().st_size != receipt["zipBytes"]:
        raise ValueError("archive reference bytes changed")
    declaration(receipt["url"], receipt["expectedOpenFile"])
    with zipfile.ZipFile(reference) as package:
        entries = package.infolist()
        if len(entries) != receipt["entries"] or sum(entry.file_size for entry in entries) != receipt["expandedBytes"]:
            raise ValueError("archive reference inventory changed")
        if (len(entries) > 20_000 or receipt["expandedBytes"] > 512 * 1024**2
                or receipt["zipBytes"] > 128 * 1024**2 or package.testzip() is not None):
            raise ValueError("archive reference exceeds the existing generation budget")
        for entry in entries:
            name = entry.filename.rstrip("/")
            if (not name or name.startswith("/") or "\\" in name or ":" in name
                    or any(part in ("", ".", "..") for part in name.split("/"))
                    or (entry.external_attr >> 16) & 0o170000 == 0o120000):
                raise ValueError("archive reference contains an unsafe path or link")
        if receipt["expectedOpenFile"] not in package.namelist():
            raise ValueError("archive reference open file is absent")
    return receipt


def verify_extracted_reference(reference: Path, target: Path) -> dict:
    """Compare actual HTTPS output against every fixed upstream input file."""
    rows = {}
    with zipfile.ZipFile(reference) as package:
        for entry in package.infolist():
            if entry.is_dir():
                continue
            actual = confined(target, entry.filename)
            expected = hashlib.sha256(package.read(entry)).hexdigest()
            if sha256(actual) != expected:
                raise AssertionError("downloaded archive bytes differ: " + entry.filename)
            rows[entry.filename] = expected
    return rows


def generate(root: Path, archive_url: str, archive_open_file: str, *, reference: Path | None = None,
             receipt_path: Path | None = None) -> dict:
    check_output(root)
    manifest = declaration(archive_url, archive_open_file)
    revision, inventory = source_revision(), source_inventory()
    root.mkdir(parents=True, exist_ok=False)
    archive = root / "generators.zip"
    write_archive(archive, {"plugin.json": json_bytes(manifest), **FILES})
    for directory in ("workspace", "projects"):
        (root / directory).mkdir()
    if bool(reference) != bool(receipt_path):
        raise ValueError("archive reference and receipt must be supplied together")
    integration = archive_input(receipt_path, reference) if reference else None
    if integration and (archive_url != integration["url"] or archive_open_file != integration["expectedOpenFile"]):
        raise ValueError("archive manifest and integration receipt differ")
    plan = {"schemaVersion": 1, "kind": "controlled-unsigned-generators", "pluginId": PLUGIN_ID,
            "sourceCommit": revision, "sourceInventory": inventory, "generatorSha256": sha256(Path(__file__)),
            "archiveURL": archive_url, "archiveOpenFile": archive_open_file,
            "archive": {"path": archive.name, "sha256": sha256(archive)}, "requires": dict(REQUIRES),
            "archiveInput": integration, "archiveReference": str(reference.resolve()) if reference else None,
            "archiveReceipt": str(receipt_path.resolve()) if receipt_path else None}
    (root / "plan.json").write_bytes(json_bytes(plan))
    return plan


def load_plan(root: Path) -> dict:
    check_output(root)
    ordinary_tree(root)
    plan = json.loads((root / "plan.json").read_text(encoding="utf-8"))
    expected = {"schemaVersion": 1, "kind": "controlled-unsigned-generators", "pluginId": PLUGIN_ID,
                "sourceCommit": source_revision(), "sourceInventory": source_inventory(),
                "generatorSha256": sha256(Path(__file__)), "archiveURL": plan["archiveURL"],
                "archiveOpenFile": plan["archiveOpenFile"],
                "archive": {"path": "generators.zip", "sha256": sha256(root / "generators.zip")},
                "requires": dict(REQUIRES), "archiveInput": plan["archiveInput"],
                "archiveReference": plan["archiveReference"], "archiveReceipt": plan["archiveReceipt"]}
    if plan != expected:
        raise ValueError("generator source/manifest/archive identity changed")
    if plan["archiveReference"]:
        actual = archive_input(Path(plan["archiveReceipt"]), Path(plan["archiveReference"]))
        if actual != plan["archiveInput"] or actual["url"] != plan["archiveURL"] or actual["expectedOpenFile"] != plan["archiveOpenFile"]:
            raise ValueError("archive integration identity changed")
    files = {"plugin.json": json_bytes(declaration(plan["archiveURL"], plan["archiveOpenFile"])), **FILES}
    with zipfile.ZipFile(confined(root, plan["archive"]["path"])) as archive:
        if sorted(archive.namelist()) != sorted(files) or any(archive.read(name) != data for name, data in files.items()):
            raise ValueError("complete controlled generator package content changed")
    return plan


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument("--archive-url", required=True)
    parser.add_argument("--archive-open-file", required=True)
    parser.add_argument("--archive-reference", type=Path)
    parser.add_argument("--archive-receipt", type=Path)
    args = parser.parse_args()
    print(json.dumps(generate(args.output, args.archive_url, args.archive_open_file,
                              reference=args.archive_reference, receipt_path=args.archive_receipt), indent=2))
