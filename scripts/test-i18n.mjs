test(
  "macOS packaging discovers new locales and preserves the source baseline",
  { timeout: 15000, skip: process.platform !== "darwin" },
  async (t) => {
    const root = await fixture(t);
    await addLocale(root);
    await generate(root);
    const { outputs } = await planGeneration(root);
    const script = path.join(root, "scripts/package-macos-localizations.sh");
    const destination = path.join(root, "packaged.bundle/Contents/Resources");
    for (let attempt = 0; attempt < 2; attempt++) {
      const result = spawnSync(
        "/bin/zsh",
        [script, path.join(root, "macos/Resources"), destination],
        { encoding: "utf8", timeout: 5000 },
      );
      assert.equal(result.status, 0, `${result.error ?? ""}\n${result.stderr}`);
    }
    for (const id of ["en", "zh-Hans", "ja"]) {
      const packaged = await readFile(path.join(destination, `${id}.lproj/Localizable.strings`));
      assert.equal(packaged.subarray(0, 8).toString(), "bplist00");
    }
    for (const [relative, expected] of outputs)
      assert.equal(await readFile(path.join(root, relative), "utf8"), expected);
  },
);

test(
  "native aliases require complete positions and reject mixed or repeated slots",
  { timeout: 15000 },
  async (t) => {
    const root = await fixture(t);
    await edit(root, "shared/i18n/messages.json", (data) => data.messages.push({
      id: "fixture.positionedAlias",
      description: "Native argument-position validation fixture.",
      platforms: ["macos"],
      parameters: { name: "string", count: "integer" },
      macos: { key: "%2$lld / %1$@", arguments: ["name", "count"] },
    }));
    for (const locale of ["en-US", "zh-CN"])
      await edit(root, `shared/i18n/locales/${locale}.json`, (data) => {
        data.messages["fixture.positionedAlias"] = "{name} / {count}";
      });
    await generate(root);
    for (const key of ["%1$@ / %lld", "%1$@ / %1$@", "%1$@ / %3$lld"]) {
      await edit(root, "shared/i18n/messages.json", (data) => {
        data.messages.find((message) => message.id === "fixture.positionedAlias").macos.key = key;
      });
      await assert.rejects(generate(root), /alias format/);
    }
  },
);

