//! Versioned local-history snapshots with bounded retention and storage validation.

use crate::project::files::VisibilityRules;
use crate::protocol::{invalid_relative_path, CoreError, ErrorCode};
use crate::protocol::{HistoryEntriesResponse, HistoryEntryResponse};
use serde::{Deserialize, Serialize};
use std::collections::HashMap;
use std::fs;
use std::path::{Path, PathBuf};
use std::sync::{Mutex, OnceLock};
use std::time::{SystemTime, UNIX_EPOCH};

const MAX_FILE_SIZE: usize = 2 * 1024 * 1024;
const MAX_ENTRIES_PER_FILE: usize = 100;
const RETENTION_SECONDS: i64 = 30 * 24 * 60 * 60;
const HISTORY_VERSION: u32 = 2;
/// Upper bound for one project's history storage, measured in allocated blocks.
const MAX_STORAGE_BYTES: u64 = 100 * 1024 * 1024;
/// Baseline snapshots stop here so edits always keep headroom under the cap and
/// reopening a project does not churn baselines through eviction.
const MAX_BASELINE_STORAGE_BYTES: u64 = MAX_STORAGE_BYTES / 2;
/// Small files still occupy whole filesystem blocks; counting blocks keeps the
/// budget close to what Finder and disk cleaners report.
const STORAGE_BLOCK_BYTES: u64 = 4096;
/// Dependency, cache, and build output directories that a baseline never needs.
///
/// Like IDEA's excluded roots, these are regenerated by tools rather than
/// edited, yet a single virtual environment holds tens of thousands of files.
/// The list repeats the built-in hidden folders so pruning also reclaims
/// baselines that releases before those rules recorded, and adds tool caches
/// and agent worktrees that stay visible in the project tree.
const BASELINE_EXCLUDED_DIRECTORY_NAMES: &[&str] = &[
    ".artifacts",
    ".build",
    ".cache",
    ".claude",
    ".git",
    ".gradle",
    ".idea",
    ".mypy_cache",
    ".next",
    ".nuxt",
    ".pytest_cache",
    ".ruff_cache",
    ".swiftpm",
    ".svn",
    ".tox",
    ".uv-cache",
    ".venv",
    ".worktree",
    ".worktrees",
    "DerivedData",
    "Pods",
    "__pycache__",
    "build",
    "coverage",
    "design-qa-artifacts",
    "dist",
    "node_modules",
    "out",
    "target",
    "venv",
];

#[derive(Debug, Deserialize)]
#[serde(rename_all = "camelCase")]
/// Snapshot contents, reason, visibility, and retention policy for one record.
pub struct HistoryRecordRequest {
    pub workspace_root: String,
    pub storage_root: String,
    pub path: String,
    pub reason: String,
    #[serde(default)]
    pub content: Option<String>,
    #[serde(default = "default_prune_expired")]
    pub prune_expired: bool,
    #[serde(default)]
    pub hidden_directory_names: Vec<String>,
    #[serde(default)]
    pub hidden_file_patterns: Vec<String>,
}

#[derive(Debug, Deserialize)]
#[serde(rename_all = "camelCase")]
/// Optional file filter and visibility policy for listing snapshot metadata.
pub struct HistoryEntriesRequest {
    pub workspace_root: String,
    pub storage_root: String,
    #[serde(default)]
    pub path: Option<String>,
    #[serde(default)]
    pub hidden_directory_names: Vec<String>,
    #[serde(default)]
    pub hidden_file_patterns: Vec<String>,
}

#[derive(Debug, Deserialize)]
#[serde(rename_all = "camelCase")]
/// Validated storage-relative path of snapshot content to read.
pub struct HistoryContentRequest {
    pub storage_root: String,
    pub content_path: String,
}

