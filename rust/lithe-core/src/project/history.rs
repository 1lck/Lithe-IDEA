#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
struct StoredEntry {
    version: u32,
    id: String,
    timestamp: i64,
    relative_path: String,
    reason: String,
    content_path: String,
    byte_count: usize,
    #[serde(default)]
    label: Option<String>,
}

/// Records a snapshot unless the path is hidden, unchanged, or too large.
pub fn record(request: HistoryRecordRequest) -> Result<Option<HistoryEntryResponse>, CoreError> {
    let workspace = existing_root(&request.workspace_root)?;
    let relative_path = safe_relative_path(&request.path)?;
    if !is_valid_reason(&request.reason) {
        return Err(CoreError::new(
            ErrorCode::InvalidRequest,
            "Unsupported local history reason",
        ));
    }
    let rules = VisibilityRules::new(request.hidden_directory_names, request.hidden_file_patterns);
    if rules.is_hidden(&relative_path, false)
        || ignored_rule(&request.ignore_rules, &relative_path).is_some()
    {
        return Ok(None);
    }
    if request.reason == "projectBaseline" && is_excluded_from_baseline(&workspace, &relative_path)
    {
        return Ok(None);
    }
    let content = match request.content {
        Some(content) => content.into_bytes(),
        None => {
            let file = workspace
                .join(&relative_path)
                .canonicalize()
                .map_err(CoreError::from)?;
            if !file.starts_with(&workspace) {
                return Err(CoreError::new(
                    ErrorCode::PermissionDenied,
                    "Path is outside the workspace",
                ));
            }
            // Baseline collection visits every visible workspace file. Reject
            // directories and oversized assets before `fs::read` so a large
            // movie/archive is never loaded only to be discarded afterward.
            let metadata = fs::metadata(&file).map_err(CoreError::from)?;
            if !metadata.is_file() || metadata.len() > MAX_FILE_SIZE as u64 {
                return Ok(None);
            }
            fs::read(file).map_err(CoreError::from)?
        }
    };
    if content.len() > MAX_FILE_SIZE {
        return Ok(None);
    }
    let Ok(text) = std::str::from_utf8(&content) else {
        return Ok(None);
    };
    if !crate::project::is_plain_text(text) {
        return Ok(None);
    }
    let storage = storage_root(&request.storage_root)?;
    let limit = storage_limit(request.storage_limit_bytes);
    let lock = storage_lock(&storage);
    let _guard = lock.lock().unwrap_or_else(|poisoned| poisoned.into_inner());
    let is_baseline = request.reason == "projectBaseline";
    if is_baseline && storage_usage(&storage) >= baseline_budget(limit) {
        return Ok(None);
    }
    let directory = storage.join(stable_identifier(&relative_path));
    fs::create_dir_all(&directory)?;
    let entries = read_entries(&directory, &storage);
    if let Some(latest) = entries.first() {
        if fs::read(storage.join(&latest.content_path)).ok().as_deref() == Some(content.as_slice())
        {
            return Ok(None);
        }
    }
    let timestamp = unix_seconds();
    let raw_id = format!("{:032x}", timestamp as u128 * 1_000_000 + monotonic_nonce());
    let id = format!(
        "{}-{}-{}-{}-{}",
        &raw_id[0..8],
        &raw_id[8..12],
        &raw_id[12..16],
        &raw_id[16..20],
        &raw_id[20..32]
    );
    let content_path = format!("{}/{}.snapshot", stable_identifier(&relative_path), id);
    let metadata_path = directory.join(format!("{}.json", id));
    let stored = StoredEntry {
        version: HISTORY_VERSION,
        id: id.clone(),
        timestamp,
        relative_path,
        reason: request.reason,
        content_path,
        byte_count: content.len(),
        label: None,
    };
    let metadata = serde_json::to_vec(&stored).expect("history metadata should encode");
    let added = allocated_bytes(content.len() as u64) + allocated_bytes(metadata.len() as u64);
    let usage = storage_usage(&storage);
    if usage.saturating_add(added) > limit {
        ensure_reclaimable_usage(
            &storage,
            limit.saturating_sub(added),
            usage,
            &all_entries(&storage),
        )?;
    }
    let snapshot_path = storage.join(&stored.content_path);
    if let Err(error) = fs::write(&snapshot_path, &content) {
        invalidate_storage_usage(&storage);
        return Err(error.into());
    }
    if let Err(error) = fs::write(&metadata_path, &metadata) {
        // A failed metadata write must not leave an unaccounted snapshot behind.
        let _ = fs::remove_file(snapshot_path);
        let _ = fs::remove_file(metadata_path);
        invalidate_storage_usage(&storage);
        return Err(error.into());
    }
    adjust_storage_usage(
        &storage,
        allocated_bytes(content.len() as u64) + allocated_bytes(metadata.len() as u64),
    );
    trim_entries(&directory, &storage);
    if request.prune_expired {
        prune_expired(&storage, &request.ignore_rules);
        enforce_storage_limit(&storage, limit)?;
    }
    Ok(Some(stored.into_response()))
}

/// Lists retained entries in newest-first deterministic order.
pub fn entries(request: HistoryEntriesRequest) -> Result<HistoryEntriesResponse, CoreError> {
    let workspace = existing_root(&request.workspace_root)?;
    let rules = VisibilityRules::new(request.hidden_directory_names, request.hidden_file_patterns);
    let storage = storage_root(&request.storage_root)?;
    let mut values = Vec::new();
    if let Some(path) = request.path {
        let relative = safe_relative_path(&path)?;
        if !rules.is_hidden(&relative, false) {
            let directory = storage.join(stable_identifier(&relative));
            values.extend(read_entries(&directory, &storage));
        }
    } else {
        for directory in fs::read_dir(&storage)?.filter_map(Result::ok) {
            if directory
                .file_type()
                .map(|value| value.is_dir())
                .unwrap_or(false)
            {
                values.extend(read_entries(&directory.path(), &storage));
            }
        }
        values.retain(|entry| {
            workspace.join(&entry.relative_path).starts_with(&workspace)
                && !rules.is_hidden(&entry.relative_path, false)
        });
    }
    values.sort_by(|left, right| {
        right
            .timestamp
            .cmp(&left.timestamp)
            .then_with(|| right.id.cmp(&left.id))
            .then_with(|| left.relative_path.cmp(&right.relative_path))
    });
    Ok(HistoryEntriesResponse {
        entries: values.into_iter().map(StoredEntry::into_response).collect(),
    })
}

/// Reads one validated snapshot content file as UTF-8.
pub fn content(request: HistoryContentRequest) -> Result<String, CoreError> {
    let storage = storage_root(&request.storage_root)?;
    let relative = safe_relative_path(&request.content_path)?;
    let data = fs::read(storage.join(relative)).map_err(CoreError::from)?;
    Ok(String::from_utf8_lossy(&data).into_owned())
}

/// Moves history metadata between workspace-relative paths.
pub fn relocate(request: HistoryRelocateRequest) -> Result<(), CoreError> {
    let storage = storage_root(&request.storage_root)?;
    let lock = storage_lock(&storage);
    let _guard = lock.lock().unwrap_or_else(|poisoned| poisoned.into_inner());
    let source = safe_relative_path(&request.source_path)?;
    let destination = safe_relative_path(&request.destination_path)?;
    let source_directory = storage.join(stable_identifier(&source));
    if !source_directory.exists() {
        return Ok(());
    }
    let destination_directory = storage.join(stable_identifier(&destination));
    fs::create_dir_all(&destination_directory)?;
    for entry in read_entries(&source_directory, &storage) {
        let content_name = format!("{}.snapshot", entry.id);
        let metadata_name = format!("{}.json", entry.id);
        let content_path = destination_directory.join(&content_name);
        fs::rename(storage.join(&entry.content_path), &content_path)?;
        let relocated = StoredEntry {
            relative_path: destination.clone(),
            content_path: format!("{}/{}", stable_identifier(&destination), content_name),
            ..entry
        };
        fs::write(
            destination_directory.join(metadata_name),
            serde_json::to_vec(&relocated).expect("history metadata should encode"),
        )?;
    }
    let _ = fs::remove_dir_all(source_directory);
    invalidate_storage_usage(&storage);
    Ok(())
}

/// Updates the optional user label for one stored snapshot.
pub fn rename(request: HistoryRenameRequest) -> Result<HistoryEntryResponse, CoreError> {
    let storage = storage_root(&request.storage_root)?;
    let lock = storage_lock(&storage);
    let _guard = lock.lock().unwrap_or_else(|poisoned| poisoned.into_inner());
    let relative = safe_relative_path(&request.path)?;
    validate_entry_id(&request.id)?;
    let directory = storage.join(stable_identifier(&relative));
    let metadata_path = directory.join(format!("{}.json", request.id));
    let data = fs::read(&metadata_path).map_err(CoreError::from)?;
    let mut entry: StoredEntry = serde_json::from_slice(&data).map_err(|error| {
        CoreError::new(ErrorCode::ParseFailed, "Invalid local history metadata")
            .with_details(error.to_string())
    })?;
    if entry.id != request.id || entry.relative_path != relative {
        return Err(CoreError::new(
            ErrorCode::InvalidRequest,
            "Local history entry does not match the requested path",
        ));
    }
    entry.label = request.label.filter(|label| !label.trim().is_empty());
    fs::write(
        metadata_path,
        serde_json::to_vec(&entry).expect("history metadata should encode"),
    )?;
    Ok(entry.into_response())
}

/// Removes one stored snapshot and its metadata.
pub fn delete(request: HistoryDeleteRequest) -> Result<(), CoreError> {
    let storage = storage_root(&request.storage_root)?;
    let lock = storage_lock(&storage);
    let _guard = lock.lock().unwrap_or_else(|poisoned| poisoned.into_inner());
    let relative = safe_relative_path(&request.path)?;
    validate_entry_id(&request.id)?;
    let directory = storage.join(stable_identifier(&relative));
    let metadata_path = directory.join(format!("{}.json", request.id));
    let data = fs::read(&metadata_path).map_err(CoreError::from)?;
    let entry: StoredEntry = serde_json::from_slice(&data).map_err(|error| {
        CoreError::new(ErrorCode::ParseFailed, "Invalid local history metadata")
            .with_details(error.to_string())
    })?;
    if entry.id != request.id || entry.relative_path != relative {
        return Err(CoreError::new(
            ErrorCode::InvalidRequest,
            "Local history entry does not match the requested path",
        ));
    }
    fs::remove_file(storage.join(entry.content_path)).map_err(CoreError::from)?;
    fs::remove_file(metadata_path).map_err(CoreError::from)?;
    invalidate_storage_usage(&storage);
    if directory
        .read_dir()
        .map(|mut entries| entries.next().is_none())
        .unwrap_or(false)
    {
        let _ = fs::remove_dir(directory);
    }
    Ok(())
}

/// Validates ignore rules and reports which rule, if any, skips `path`.
pub fn ignore_preview(
    request: HistoryIgnorePreviewRequest,
) -> Result<HistoryIgnorePreviewResponse, CoreError> {
    let regex_errors = request
        .ignore_rules
        .path_regexes
        .iter()
        .enumerate()
        .filter(|(_, pattern)| !pattern.trim().is_empty())
        .filter_map(|(index, pattern)| {
            build_ignore_regex(pattern.trim())
                .err()
                .map(|error| HistoryIgnoreRegexError {
                    index,
                    message: error.to_string(),
                })
        })
        .collect();
    let (matched, git_ignored) = match request.path.as_deref().map(str::trim) {
        Some(path) if !path.is_empty() => {
            let relative = safe_relative_path(path)?;
            let matched = preview_match(
                &request.ignore_rules,
                &request.hidden_file_patterns,
                &relative,
            );
            // A missing workspace only loses the Git line, not the rule preview.
            let git_ignored = match request.workspace_root.as_deref().map(existing_root) {
                Some(Ok(root)) => {
                    crate::git::ignored_paths(&root, std::slice::from_ref(&relative))?
                        .map(|ignored| ignored.contains(&relative))
                }
                _ => None,
            };
            (matched, git_ignored)
        }
        _ => (None, None),
    };
    Ok(HistoryIgnorePreviewResponse {
        regex_errors,
        built_in_ignore_patterns: BUILT_IN_IGNORED_DIRECTORY_NAMES
            .iter()
            .map(|name| built_in_ignore_pattern(name))
            .collect(),
        matched,
        git_ignored,
    })
}

/// Reports one project's allocated history size, rescanning the disk.
pub fn usage(request: HistoryStorageRequest) -> Result<HistoryUsageResponse, CoreError> {
    let storage = storage_root(&request.storage_root)?;
    let lock = storage_lock(&storage);
    let _guard = lock.lock().unwrap_or_else(|poisoned| poisoned.into_inner());
    invalidate_storage_usage(&storage);
    Ok(HistoryUsageResponse {
        used_bytes: storage_usage(&storage),
        limit_bytes: storage_limit(request.storage_limit_bytes),
    })
}

/// The cap to enforce: the host's value kept within sane bounds, or the default.
fn storage_limit(requested: Option<u64>) -> u64 {
    requested.map_or(MAX_STORAGE_BYTES, |bytes| {
        bytes.clamp(MIN_CONFIGURED_STORAGE_BYTES, MAX_CONFIGURED_STORAGE_BYTES)
    })
}

/// Baseline snapshots stop at half of the cap (50 MB by default) so edits always
/// keep headroom and reopening a project does not churn baselines through eviction.
fn baseline_budget(limit: u64) -> u64 {
    limit / 2
}

/// Deletes every snapshot of one project. The storage root itself stays.
pub fn clear(request: HistoryStorageRequest) -> Result<(), CoreError> {
    let storage = storage_root(&request.storage_root)?;
    let lock = storage_lock(&storage);
    let _guard = lock.lock().unwrap_or_else(|poisoned| poisoned.into_inner());
    let result = fs::read_dir(&storage)
        .map_err(CoreError::from)?
        .filter_map(Result::ok)
        .filter(|entry| entry.file_type().map(|kind| kind.is_dir()).unwrap_or(false))
        .try_for_each(|entry| fs::remove_dir_all(entry.path()));
    invalidate_storage_usage(&storage);
    result.map_err(CoreError::from)
}

fn preview_match(
    rules: &HistoryIgnoreRules,
    hidden_file_patterns: &[String],
    relative_path: &str,
) -> Option<HistoryIgnoreMatch> {
    if VisibilityRules::new(Vec::new(), hidden_file_patterns.to_vec())
        .is_hidden(relative_path, false)
    {
        return Some(HistoryIgnoreMatch::Hidden);
    }
    ignored_rule(rules, relative_path)
}

/// The first rule that matches: built-in folders, the user's globs, then regexes.
fn ignored_rule(rules: &HistoryIgnoreRules, relative_path: &str) -> Option<HistoryIgnoreMatch> {
    // Folder names are compared directly; baseline seeding asks for thousands of files.
    let mut folders = relative_path.split('/').collect::<Vec<_>>();
    folders.pop();
    let built_in = rules.built_in_ignored_directories();
    if let Some(name) = folders.iter().find_map(|folder| {
        built_in
            .iter()
            .find(|name| folder.eq_ignore_ascii_case(name))
    }) {
        return Some(HistoryIgnoreMatch::Pattern {
            pattern: built_in_ignore_pattern(name),
        });
    }
    // Built-in hidden paths are already rejected, so a hit here comes from the
    // user's own pattern.
    let found = rules
        .path_patterns
        .iter()
        .map(|pattern| pattern.trim())
        .find(|pattern| {
            !pattern.is_empty()
                && !pattern.starts_with('!')
                && VisibilityRules::new(Vec::new(), vec![pattern.to_string()])
                    .is_hidden(relative_path, false)
        });
    if let Some(pattern) = found {
        return Some(HistoryIgnoreMatch::Pattern {
            pattern: pattern.to_string(),
        });
    }
    if rules.path_regexes.is_empty() {
        return None;
    }
    compiled_ignore_regexes(&rules.path_regexes)
        .iter()
        .position(|regex| {
            regex
                .as_ref()
                .is_some_and(|regex| regex.is_match(relative_path))
        })
        .map(|index| HistoryIgnoreMatch::Regex { index })
}

fn build_ignore_regex(pattern: &str) -> Result<regex::Regex, regex::Error> {
    regex::RegexBuilder::new(pattern)
        .case_insensitive(true)
        .size_limit(1 << 20)
        .build()
}

/// Compiles the regex list once per distinct list, because baseline seeding
/// records thousands of files with the same rules.
fn compiled_ignore_regexes(patterns: &[String]) -> Arc<Vec<Option<regex::Regex>>> {
    type Compiled = (Vec<String>, Arc<Vec<Option<regex::Regex>>>);
    static CACHE: OnceLock<Mutex<Option<Compiled>>> = OnceLock::new();
    let cache = CACHE.get_or_init(|| Mutex::new(None));
    if let Ok(guard) = cache.lock() {
        if let Some((cached, compiled)) = guard.as_ref() {
            if cached.as_slice() == patterns {
                return Arc::clone(compiled);
            }
        }
    }
    let compiled = Arc::new(
        patterns
            .iter()
            .map(|pattern| {
                let trimmed = pattern.trim();
                (!trimmed.is_empty())
                    .then(|| build_ignore_regex(trimmed).ok())
                    .flatten()
            })
            .collect::<Vec<_>>(),
    );
    if let Ok(mut guard) = cache.lock() {
        *guard = Some((patterns.to_vec(), Arc::clone(&compiled)));
    }
    compiled
}

