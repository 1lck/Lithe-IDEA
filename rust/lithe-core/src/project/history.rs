    fn record_request(
        workspace: &Path,
        storage: &Path,
        path: &str,
        reason: &str,
        content: Option<&str>,
    ) -> HistoryRecordRequest {
        HistoryRecordRequest {
            workspace_root: workspace.to_string_lossy().into_owned(),
            storage_root: storage.to_string_lossy().into_owned(),
            path: path.into(),
            reason: reason.into(),
            content: content.map(str::to_string),
            prune_expired: reason != "projectBaseline",
            hidden_directory_names: Vec::new(),
            hidden_file_patterns: Vec::new(),
        }
    }

    fn write_file(root: &Path, path: &str, content: &str) {
        let file = root.join(path);
        fs::create_dir_all(file.parent().unwrap()).unwrap();
        fs::write(file, content).unwrap();
    }

    /// Writes an entry directly, as an older release that seeded every file would have.
    fn write_stored_entry(storage: &Path, path: &str, reason: &str, timestamp: i64, size: usize) {
        let id = format!("{:08x}-0000-0000-0000-{:012x}", timestamp, size);
        let directory = storage.join(stable_identifier(path));
        fs::create_dir_all(&directory).unwrap();
        let entry = StoredEntry {
            version: HISTORY_VERSION,
            id: id.clone(),
            timestamp,
            relative_path: path.into(),
            reason: reason.into(),
            content_path: format!("{}/{}.snapshot", stable_identifier(path), id),
            byte_count: size,
            label: None,
        };
        fs::write(storage.join(&entry.content_path), "x".repeat(size)).unwrap();
        fs::write(
            directory.join(format!("{id}.json")),
            serde_json::to_vec(&entry).unwrap(),
        )
        .unwrap();
    }

    fn stored_paths(storage: &Path) -> Vec<String> {
        let mut paths = all_entries(storage)
            .into_iter()
            .map(|entry| entry.relative_path)
            .collect::<Vec<_>>();
        paths.sort();
        paths
    }

    #[test]
    fn baseline_skips_generated_directories_and_nested_repositories() {
        let root = temporary_root("history-baseline-exclusions");
        let workspace = root.join("workspace");
        let storage = root.join("storage");
        write_file(&workspace, "src/main.py", "print('a')\n");
        write_file(&workspace, "tools/.uv-cache/wheel/site.py", "import os\n");
        write_file(&workspace, ".claude/worktrees/a/src/main.py", "x\n");
        write_file(&workspace, "worktrees/feature/.git", "gitdir: elsewhere\n");
        write_file(&workspace, "worktrees/feature/src/main.py", "print('b')\n");

        for path in [
            "tools/.uv-cache/wheel/site.py",
            ".claude/worktrees/a/src/main.py",
            "worktrees/feature/src/main.py",
        ] {
            let response = record(record_request(
                &workspace,
                &storage,
                path,
                "projectBaseline",
                None,
            ))
            .unwrap();
            assert!(response.is_none(), "{path} should not get a baseline");
        }
        let response = record(record_request(
            &workspace,
            &storage,
            "src/main.py",
            "projectBaseline",
            None,
        ))
        .unwrap();
        assert!(response.is_some());

        // Explicit edits inside excluded folders are still the user's history.
        let saved = record(record_request(
            &workspace,
            &storage,
            "tools/.uv-cache/wheel/site.py",
            "saved",
            Some("import sys\n"),
        ))
        .unwrap();
        assert!(saved.is_some());
        fs::remove_dir_all(root).unwrap();
    }

    #[test]
    fn saving_prunes_baselines_that_older_releases_kept_for_excluded_paths() {
        let root = temporary_root("history-legacy-baselines");
        let workspace = root.join("workspace");
        let storage = root.join("storage");
        fs::create_dir_all(&workspace).unwrap();
        let now = unix_seconds();
        write_stored_entry(&storage, ".venv/lib/site.py", "projectBaseline", now, 10);
        write_stored_entry(&storage, ".venv/lib/edited.py", "saved", now, 10);
        write_stored_entry(&storage, "src/main.py", "projectBaseline", now, 10);

        record(record_request(
            &workspace,
            &storage.canonicalize().unwrap(),
            "src/other.py",
            "saved",
            Some("x\n"),
        ))
        .unwrap();

        assert_eq!(
            stored_paths(&storage.canonicalize().unwrap()),
            [".venv/lib/edited.py", "src/main.py", "src/other.py"]
        );
        fs::remove_dir_all(root).unwrap();
    }

    #[test]
    fn storage_limit_evicts_old_baselines_before_edits_and_labels() {
        let root = temporary_root("history-storage-limit");
        let storage = root.join("storage");
        fs::create_dir_all(&storage).unwrap();
        let storage = storage.canonicalize().unwrap();
        write_stored_entry(&storage, "a/old-edit.txt", "saved", 100, 10);
        write_stored_entry(&storage, "a/old-base.txt", "projectBaseline", 200, 10);
        write_stored_entry(&storage, "a/new-base.txt", "projectBaseline", 300, 10);
        write_stored_entry(&storage, "a/new-edit.txt", "saved", 400, 10);
        let labeled = all_entries(&storage)
            .into_iter()
            .find(|entry| entry.relative_path == "a/old-edit.txt")
            .unwrap();
        fs::write(
            metadata_path(&storage, &labeled),
            serde_json::to_vec(&StoredEntry {
                label: Some("keep".into()),
                ..labeled
            })
            .unwrap(),
        )
        .unwrap();
        invalidate_storage_usage(&storage);
        // Each entry occupies two blocks: snapshot plus metadata.
        let entry_bytes = 2 * STORAGE_BLOCK_BYTES;
        assert_eq!(storage_usage(&storage), 4 * entry_bytes);

        enforce_storage_limit(&storage, 2 * entry_bytes);
        assert_eq!(stored_paths(&storage), ["a/new-edit.txt", "a/old-edit.txt"]);

        enforce_storage_limit(&storage, entry_bytes);
        assert_eq!(stored_paths(&storage), ["a/old-edit.txt"]);
        assert_eq!(storage_usage(&storage), entry_bytes);
        fs::remove_dir_all(root).unwrap();
    }

    #[test]
    fn baseline_stops_once_its_budget_is_used() {
        let root = temporary_root("history-baseline-budget");
        let workspace = root.join("workspace");
        let storage = root.join("storage");
        write_file(&workspace, "src/main.py", "print('a')\n");
        fs::create_dir_all(&storage).unwrap();
        let canonical = storage.canonicalize().unwrap();
        usage_cache()
            .lock()
            .unwrap()
            .insert(canonical.clone(), MAX_BASELINE_STORAGE_BYTES);

        let baseline = record(record_request(
            &workspace,
            &storage,
            "src/main.py",
            "projectBaseline",
            None,
        ))
        .unwrap();
        assert!(baseline.is_none());
        let saved = record(record_request(
            &workspace,
            &storage,
            "src/main.py",
            "saved",
            Some("print('b')\n"),
        ))
        .unwrap();
        assert!(saved.is_some());
        invalidate_storage_usage(&canonical);
        fs::remove_dir_all(root).unwrap();
    }
