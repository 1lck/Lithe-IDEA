const MAX_FILE_SIZE: usize = 2 * 1024 * 1024;
const MAX_ENTRIES_PER_FILE: usize = 100;
const RETENTION_SECONDS: i64 = 30 * 24 * 60 * 60;
const HISTORY_VERSION: u32 = 2;
/// Default upper bound for one project's history storage, measured in allocated blocks.
const MAX_STORAGE_BYTES: u64 = 100 * 1024 * 1024;
/// Bounds for a host-supplied cap: a tiny cap would evict every edit, and a
/// huge one would let one project fill the disk unnoticed.
const MIN_CONFIGURED_STORAGE_BYTES: u64 = 10 * 1024 * 1024;
const MAX_CONFIGURED_STORAGE_BYTES: u64 = 100 * 1024 * 1024 * 1024;
/// Small files still occupy whole filesystem blocks; counting blocks keeps the
/// budget close to what Finder and disk cleaners report.
const STORAGE_BLOCK_BYTES: u64 = 4096;
/// Dependency, cache, and build output folders local history ignores by default.
///
/// Like IDEA's excluded roots, these are regenerated by tools rather than
/// edited, yet a single virtual environment holds tens of thousands of files.
/// Settings show each as the wildcard rule `**/name/`, which the user can delete.
/// The list repeats the built-in hidden folders so pruning also reclaims
/// baselines that releases before those rules recorded, and adds tool caches
/// and agent worktrees that stay visible in the project tree.
const BUILT_IN_IGNORED_DIRECTORY_NAMES: &[&str] = &[
    ".artifacts",
    ".build",
    ".cache",
    ".claude",
    ".git",
    ".gradle",
    ".idea",
    ".mypy_cache",
    ".next",
    ".nuxt",
    ".pytest_cache",
    ".ruff_cache",
    ".swiftpm",
    ".svn",
    ".tox",
    ".uv-cache",
    ".venv",
    ".worktree",
    ".worktrees",
    "DerivedData",
    "Pods",
    "__pycache__",
    "build",
    "coverage",
    "design-qa-artifacts",
    "dist",
    "node_modules",
    "out",
    "target",
    "venv",
];

