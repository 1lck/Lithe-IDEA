#[derive(Debug, Deserialize)]
#[serde(rename_all = "camelCase")]
struct LegacyStoredEntry {
    id: String,
    timestamp: String,
    relative_path: String,
    reason: String,
    content_url: String,
    byte_count: usize,
}

fn read_entries(directory: &Path, storage: &Path) -> Vec<StoredEntry> {
    let mut entries = fs::read_dir(directory)
        .ok()
        .into_iter()
        .flatten()
        .filter_map(Result::ok)
        .filter(|entry| entry.path().extension().and_then(|value| value.to_str()) == Some("json"))
        .filter_map(|entry| {
            let data = fs::read(entry.path()).ok()?;
            if let Ok(value) = serde_json::from_slice::<StoredEntry>(&data) {
                return (value.version == HISTORY_VERSION).then_some(value);
            }
            let legacy = serde_json::from_slice::<LegacyStoredEntry>(&data).ok()?;
            let content = PathBuf::from(legacy.content_url)
                .strip_prefix(storage)
                .ok()?
                .to_string_lossy()
                .replace('\\', "/");
            Some(StoredEntry {
                version: HISTORY_VERSION,
                id: legacy.id,
                timestamp: parse_iso_timestamp(&legacy.timestamp),
                relative_path: legacy.relative_path,
                reason: legacy.reason,
                content_path: content,
                byte_count: legacy.byte_count,
                label: None,
            })
        })
        .filter(|entry| storage.join(&entry.content_path).is_file())
        .collect::<Vec<_>>();
    entries.sort_by(|left, right| {
        right
            .timestamp
            .cmp(&left.timestamp)
            .then_with(|| right.id.cmp(&left.id))
    });
    entries
}

fn validate_entry_id(id: &str) -> Result<(), CoreError> {
    if id.is_empty()
        || !id
            .chars()
            .all(|character| character.is_ascii_hexdigit() || character == '-')
    {
        return Err(CoreError::new(
            ErrorCode::InvalidRequest,
            "Invalid local history entry ID",
        ));
    }
    Ok(())
}

fn default_prune_expired() -> bool {
    true
}

fn trim_entries(directory: &Path, storage: &Path) {
    let mut removed = false;
    for entry in read_entries(directory, storage)
        .into_iter()
        .skip(MAX_ENTRIES_PER_FILE)
    {
        remove_entry(storage, &entry);
        removed = true;
    }
    if removed {
        invalidate_storage_usage(storage);
    }
}

/// Removes expired entries and baselines that current ignore rules reject.
///
/// Older releases seeded every visible file, including virtual environments and
/// nested worktrees; dropping those baselines here reclaims that space without
/// touching snapshots of real edits.
fn prune_expired(storage: &Path, rules: &HistoryIgnoreRules) {
    let cutoff = unix_seconds() - RETENTION_SECONDS;
    let mut removed = false;
    for entry in all_entries(storage) {
        let excluded_baseline = entry.reason == "projectBaseline"
            && ignored_rule(rules, &entry.relative_path).is_some();
        if entry.timestamp < cutoff || excluded_baseline {
            remove_entry(storage, &entry);
            removed = true;
        }
    }
    if removed {
        invalidate_storage_usage(storage);
    }
}

/// Evicts snapshots until the storage fits `limit`.
///
/// Baselines go first because saves already record the text before each edit;
/// labeled snapshots go last because the user named them deliberately. Within
/// each group the oldest snapshot is evicted first.
fn enforce_storage_limit(storage: &Path, limit: u64) -> Result<(), CoreError> {
    let mut usage = storage_usage(storage);
    if usage <= limit {
        return Ok(());
    }
    let mut entries = all_entries(storage);
    ensure_reclaimable_usage(storage, limit, usage, &entries)?;
    entries.sort_by_key(|entry| {
        (
            entry.label.is_some(),
            entry.reason != "projectBaseline",
            entry.timestamp,
            entry.id.clone(),
            entry.relative_path.clone(),
        )
    });
    for entry in entries {
        if usage <= limit {
            break;
        }
        usage = usage.saturating_sub(entry_allocated_bytes(storage, &entry));
        remove_entry(storage, &entry);
    }
    invalidate_storage_usage(storage);
    Ok(())
}

fn ensure_reclaimable_usage(
    storage: &Path,
    limit: u64,
    usage: u64,
    entries: &[StoredEntry],
) -> Result<(), CoreError> {
    let recoverable: u64 = entries
        .iter()
        .map(|entry| entry_allocated_bytes(storage, entry))
        .sum();
    // Never sacrifice valid snapshots for bytes that eviction cannot reclaim.
    if usage.saturating_sub(recoverable) > limit {
        return Err(CoreError::new(
            ErrorCode::Unknown,
            "Local history contains unrecognized files exceeding its storage limit",
        ));
    }
    Ok(())
}

fn all_entries(storage: &Path) -> Vec<StoredEntry> {
    let Ok(directories) = fs::read_dir(storage) else {
        return Vec::new();
    };
    directories
        .filter_map(Result::ok)
        .filter(|directory| {
            directory
                .file_type()
                .map(|value| value.is_dir())
                .unwrap_or(false)
        })
        .flat_map(|directory| read_entries(&directory.path(), storage))
        .collect()
}

fn remove_entry(storage: &Path, entry: &StoredEntry) {
    let _ = fs::remove_file(storage.join(&entry.content_path));
    let _ = fs::remove_file(metadata_path(storage, entry));
    if let Some(directory) = storage.join(&entry.content_path).parent() {
        // Only succeeds once the file has no snapshots left.
        let _ = fs::remove_dir(directory);
    }
}

fn metadata_path(storage: &Path, entry: &StoredEntry) -> PathBuf {
    storage
        .join(stable_identifier(&entry.relative_path))
        .join(format!("{}.json", entry.id))
}

fn entry_allocated_bytes(storage: &Path, entry: &StoredEntry) -> u64 {
    [
        storage.join(&entry.content_path),
        metadata_path(storage, entry),
    ]
    .iter()
    .filter_map(|path| fs::metadata(path).ok())
    .map(|metadata| allocated_bytes(metadata.len()))
    .sum()
}

fn allocated_bytes(length: u64) -> u64 {
    length.div_ceil(STORAGE_BLOCK_BYTES).max(1) * STORAGE_BLOCK_BYTES
}

// All mutations of a storage root share a lock, including cold scans and eviction.
fn storage_lock(storage: &Path) -> Arc<Mutex<()>> {
    static LOCKS: OnceLock<Mutex<HashMap<PathBuf, Weak<Mutex<()>>>>> = OnceLock::new();
    let mut locks = LOCKS
        .get_or_init(|| Mutex::new(HashMap::new()))
        .lock()
        .unwrap_or_else(|poisoned| poisoned.into_inner());
    locks.retain(|_, lock| lock.strong_count() > 0);
    if let Some(lock) = locks.get(storage).and_then(Weak::upgrade) {
        return lock;
    }
    let lock = Arc::new(Mutex::new(()));
    locks.insert(storage.to_path_buf(), Arc::downgrade(&lock));
    lock
}

/// Process-wide usage per storage root, so baseline seeding checks the budget
/// without rescanning tens of thousands of snapshot files for every record.
fn usage_cache() -> &'static Mutex<HashMap<PathBuf, u64>> {
    static CACHE: OnceLock<Mutex<HashMap<PathBuf, u64>>> = OnceLock::new();
    CACHE.get_or_init(|| Mutex::new(HashMap::new()))
}

fn storage_usage(storage: &Path) -> u64 {
    if let Some(value) = usage_cache()
        .lock()
        .ok()
        .and_then(|cache| cache.get(storage).copied())
    {
        return value;
    }
    let value = scan_storage_usage(storage);
    if let Ok(mut cache) = usage_cache().lock() {
        cache.insert(storage.to_path_buf(), value);
    }
    value
}

fn scan_storage_usage(storage: &Path) -> u64 {
    let Ok(directories) = fs::read_dir(storage) else {
        return 0;
    };
    directories
        .filter_map(Result::ok)
        .filter_map(|directory| fs::read_dir(directory.path()).ok())
        .flatten()
        .filter_map(Result::ok)
        .filter_map(|file| file.metadata().ok())
        .filter(|metadata| metadata.is_file())
        .map(|metadata| allocated_bytes(metadata.len()))
        .sum()
}

fn adjust_storage_usage(storage: &Path, added: u64) {
    if let Ok(mut cache) = usage_cache().lock() {
        if let Some(value) = cache.get_mut(storage) {
            *value += added;
        }
    }
}

fn invalidate_storage_usage(storage: &Path) {
    if let Ok(mut cache) = usage_cache().lock() {
        cache.remove(storage);
    }
}

/// Rejects files owned by a nested repository.
///
/// A nested `.git` marks another checkout, such as a worktree or vendored clone,
/// whose files belong to that repository's own history rather than this project.
fn is_excluded_from_baseline(workspace: &Path, relative_path: &str) -> bool {
    let mut directory = workspace.to_path_buf();
    let mut components = relative_path.split('/').collect::<Vec<_>>();
    components.pop();
    components.into_iter().any(|component| {
        directory.push(component);
        directory.join(".git").exists()
    })
}

fn existing_root(value: &str) -> Result<PathBuf, CoreError> {
    let path = PathBuf::from(value);
    let metadata = fs::metadata(&path)
        .map_err(|_| CoreError::new(ErrorCode::WorkspaceNotFound, "Workspace does not exist"))?;
    if !metadata.is_dir() {
        return Err(CoreError::new(
            ErrorCode::InvalidRequest,
            "Workspace root must be a directory",
        ));
    }
    path.canonicalize().map_err(CoreError::from)
}

fn storage_root(value: &str) -> Result<PathBuf, CoreError> {
    let path = PathBuf::from(value);
    fs::create_dir_all(&path).map_err(CoreError::from)?;
    path.canonicalize().map_err(CoreError::from)
}

fn safe_relative_path(value: &str) -> Result<String, CoreError> {
    let path = Path::new(value);
    if path.is_absolute() || invalid_relative_path(value) {
        return Err(CoreError::new(
            ErrorCode::InvalidRequest,
            "Path must be relative",
        ));
    }
    let normalized = value.replace('\\', "/").trim_matches('/').to_string();
    if normalized.is_empty() {
        return Err(CoreError::new(
            ErrorCode::InvalidRequest,
            "Path must not be empty",
        ));
    }
    Ok(normalized)
}

fn stable_identifier(value: &str) -> String {
    let mut hash: u64 = 14_695_981_039_346_656_037;
    for byte in value.as_bytes() {
        hash ^= u64::from(*byte);
        hash = hash.wrapping_mul(1_099_511_628_211);
    }
    format!("{hash:x}")
}

fn unix_seconds() -> i64 {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|value| value.as_secs() as i64)
        .unwrap_or_default()
}

fn monotonic_nonce() -> u128 {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|value| value.subsec_nanos() as u128)
        .unwrap_or_default()
}

fn is_valid_reason(value: &str) -> bool {
    matches!(
        value,
        "projectBaseline"
            | "saved"
            | "externalChange"
            | "beforeRename"
            | "beforeDelete"
            | "beforeBatchReplace"
            | "unsavedDiscard"
            | "restored"
    )
}

fn parse_iso_timestamp(value: &str) -> i64 {
    if value.len() < 19 {
        return 0;
    }
    let number = |start: usize, end: usize| -> i64 {
        value
            .get(start..end)
            .and_then(|part| part.parse::<i64>().ok())
            .unwrap_or_default()
    };
    let year = number(0, 4);
    let month = number(5, 7);
    let day = number(8, 10);
    let hour = number(11, 13);
    let minute = number(14, 16);
    let second = number(17, 19);
    let adjusted_year = year - i64::from(month <= 2);
    let era = (if adjusted_year >= 0 {
        adjusted_year
    } else {
        adjusted_year - 399
    }) / 400;
    let year_of_era = adjusted_year - era * 400;
    let month_index = month + if month > 2 { -3 } else { 9 };
    let day_of_year = (153 * month_index + 2) / 5 + day - 1;
    let day_of_era = year_of_era * 365 + year_of_era / 4 - year_of_era / 100 + day_of_year;
    let days = era * 146_097 + day_of_era - 719_468;
    days * 86_400 + hour * 3_600 + minute * 60 + second
}

