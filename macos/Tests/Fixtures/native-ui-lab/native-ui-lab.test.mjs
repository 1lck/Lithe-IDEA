import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { readFile } from 'node:fs/promises';
import { test } from 'node:test';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { join, resolve } from 'node:path';
const sdkRoot = process.env.LITHE_PLUGIN_SDK_ROOT;
if (!sdkRoot) throw new Error('Set LITHE_PLUGIN_SDK_ROOT to the lithe-plugin-docs/sdk/node directory.');
const { TestHost } = await import(pathToFileURL(join(resolve(sdkRoot), 'test/harness.mjs')).href);

const example = fileURLToPath(new URL('../../../../.artifacts/native-ui-lab/NativeUILab/', import.meta.url));
const packageRoot = process.env.LITHE_UI_LAB_PACKAGE ?? example;

test('UI lab exposes every declared action and exercises data mutations and recoverable failures', { timeout: 15000 }, async (t) => {
  const child = spawn(process.execPath, [join(packageRoot, 'backend/main.mjs')], { stdio: 'pipe' });
  const host = new TestHost(child);
  t.after(async () => { try { await host.close(); } finally { if (child.exitCode === null) child.kill('SIGKILL'); } });
  const initialized = await host.initialize();
  assert.equal(initialized.error, undefined);
  let operation = 0;
  const invoke = (functionID, params = {}) => host.request('lithe/function/invoke', { functionID, operationID: `lab-${++operation}`, params });
  const result = async (id, params) => {
    const reply = await invoke(id, params);
    assert.equal(reply.error, undefined, JSON.stringify(reply.error));
    return reply.result;
  };
  const manifest = JSON.parse(await readFile(join(packageRoot, 'plugin.json'), 'utf8'));
  assert.equal(manifest.ui.toolWindows.length, 7);
  assert.deepEqual(new Set(manifest.ui.toolWindows.map((panel) => panel.placement)), new Set(['left', 'right', 'bottom']));
  const offered = new Set(initialized.result.capabilities.experimental.litheFunctions.functions.map((fn) => fn.id));
  for (const panel of manifest.ui.toolWindows) {
    if (panel.native.source) assert.ok(offered.has(panel.native.source.function));
    for (const action of panel.native.actions) if (action.function) assert.ok(offered.has(action.function), action.function);
  }
  const form = manifest.ui.toolWindows.find((panel) => panel.native.kind === 'form').native;
  assert.deepEqual(new Set(form.controls.map((control) => control.kind)), new Set(['input', 'search', 'editor', 'select', 'segmented', 'checkbox', 'stepper']));
  assert.deepEqual(form.layout, { columns: 12 });
  assert.deepEqual(form.controls.slice(0, 3).map((control) => control.span), [6, 6, 6]);
  assert.ok(form.controls.every((control) => control.span >= 1 && control.span <= form.layout.columns));
  assert.equal(form.toolbar.length, 0, 'Form actions must remain separate from header actions');
  assert.deepEqual(new Set(form.buttons.map((button) => button.width ?? 'content')), new Set(['content']));
  assert.ok(form.controls.every((control) => control.info));
  assert.equal(manifest.version, '0.3.4');
  assert.ok(form.controls.filter((control) => control.enabled === false).every((control) => control.info.includes('键盘')));
  assert.ok(form.buttons.filter((button) => button.enabled === false).every((button) => button.info));
  for (const button of form.buttons) assert.ok(form.actions.some((action) => action.id === button.action));
  const buttonsOnly = manifest.ui.toolWindows.find((panel) => panel.native.id === 'buttons').native;
  assert.deepEqual(buttonsOnly.controls, []);
  assert.equal(buttonsOnly.buttons.length, 8);
  assert.deepEqual(buttonsOnly.buttons.filter((button) => button.enabled === false).map((button) => button.primary ?? false), [false, true]);
  assert.match((await result('buttons.inspect')).message, /0\.3\.4/);
  const values = Object.fromEntries(form.controls.map((control) => [control.id, control.value]));
  Object.assign(values, { name: '中文 😀 / English', query: '输入值', environment: 'prod', notify: false });
  const reply = await result('form.changed', { values, selectedID: null });
  assert.deepEqual(JSON.parse(reply.message.replace('已收到：', '')), values);
  assert.deepEqual(await result('form.nodes', { values }), { nodes: [] });
  assert.equal((await invoke('form.changed', { values: { ...values, notify: 'invalid' } })).error.data.code, 'lab.form');
  assert.equal((await invoke('form.changed', { values: { ...values, concurrency: 9 } })).error.data.code, 'lab.form');
  assert.equal((await invoke('form.fail', { values })).error.data.code, 'lab.form.expected');
  const formPending = host.request('lithe/function/invoke', { functionID: 'form.slow', operationID: 'cancel-form', params: { values } }, 'cancel-form');
  await host.waitFor((message) => message.method === 'lithe/function/progress' && message.params.operationID === 'cancel-form', 'form slow commit to reach its cancellable wait');
  host.notify('$/cancelRequest', { id: 'cancel-form' });
  assert.equal((await formPending).error.code, -32800);
  const flatten = (nodes) => nodes.flatMap((node) => [node, ...flatten(node.children ?? [])]);
  for (const kind of ['tree', 'list']) {
    const read = () => result(`${kind}.nodes`);
    const initial = await read();
    const selectedID = flatten(initial.nodes).at(-1).id;
    assert.match((await result(`${kind}.inspect`, { selectedID })).message, new RegExp(selectedID));
    await result(`${kind}.rename`, { selectedID });
    assert.ok(flatten((await read()).nodes).find((n) => n.id === selectedID).label.endsWith(' ✓'));
    await result(`${kind}.reverse`);
    assert.ok(flatten((await read()).nodes).some((n) => n.id === selectedID));
    await result(`${kind}.add`);
    assert.ok((await read()).nodes.some((n) => n.id === 'added-1'));
    await result(`${kind}.remove`, { selectedID });
    assert.ok(!flatten((await read()).nodes).some((n) => n.id === selectedID));
    assert.equal((await invoke(`${kind}.inspect`, { selectedID })).error.data.code, 'lab.selection');
    await result(`${kind}.empty`);
    assert.deepEqual((await read()).nodes, []);
    await result(`${kind}.reset`);
    assert.deepEqual(await read(), initial);
    await result(`${kind}.large`);
    const large = await read();
    assert.equal(large.nodes.length, 600);
    assert.equal(new Set(flatten(large.nodes).map((n) => n.id)).size, kind === 'tree' ? 1200 : 600);
    assert.equal((await invoke(`${kind}.fail`)).error.data.code, 'lab.expected');
    assert.deepEqual(await read(), large);
    await result(`${kind}.sourceError`);
    assert.equal((await invoke(`${kind}.nodes`)).error.data.code, 'lab.source');
    await result(`${kind}.reset`);
    await result(`${kind}.invalid`);
    assert.equal(new Set((await read()).nodes.map((n) => n.id)).size, 1);
    await result(`${kind}.reset`);
    assert.deepEqual(await read(), initial);
    const operationID = `cancel-${kind}`;
    const pending = host.request('lithe/function/invoke', { functionID: `${kind}.slow`, operationID, params: {} }, operationID);
    await host.waitFor((message) => message.method === 'lithe/function/progress' && message.params.operationID === operationID, 'slow action to reach its cancellable wait');
    host.notify('$/cancelRequest', { id: operationID });
    assert.equal((await pending).error.code, -32800);
    assert.deepEqual(await read(), initial);
  }
});
