export type TranslationKey = keyof (typeof catalogs)["en-US"];

export function getLocaleCatalog(language: DisplayLanguage) {
  return catalogs[language];
}

export function createTranslator(language: DisplayLanguage) {
  const catalog = getLocaleCatalog(language);

  return (key: string, values?: Record<string, string | number>): string => {
    let translatedText: string = catalog[key as TranslationKey] ?? key;

    for (const [name, value] of Object.entries(values ?? {})) {
      translatedText = translatedText.split(`{${name}}`).join(String(value));
    }

    return translatedText;
  };
}
